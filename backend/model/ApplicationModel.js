import mongoose from "mongoose";
const applicationSchema=new mongoose.Schema(
    {
        user:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"User",
            required:true,
            unique:true
        },
        name:{
            type:String,
            required:true,
            trim:true,
        },
        email:{
            type:String,
            required:true,
            trim:true,
            lowercase:true
        },
        phone:{
            type:String,
            required:true
        },
        degree:{
            type:String,
            required:true
        },
        branch:{
            type:String,
            required:true
        },
        college:{
            type:String,
            required:true
        },
        graduationYear:{
            type:String,
            required:true
        },
        skills:{
            type:String,
            required:true
        },
        internship:{
            type:String,
            default:""
        },
        internshipDuration:{
            type:String,
            default:""
        },
        workExperience:{
            type:String,
            default:""
        },
        workDetails:{
            type:String,
            default:""
        },
        certifications:{
            type:String,
            default:""
        },
        achievements:{
            type:String,
            default:""
        },
        interestedRoles:{
            type:String,
            required:true
        },
        preferredRole:{
            type:String,
            default:""
        },
        resume:{
            fileName:String,
            filePath:String
        }
    },
    {
        timestamps:true
    }

);
const Application=mongoose.model("Application",applicationSchema);
export default Application